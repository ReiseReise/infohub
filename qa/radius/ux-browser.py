import json,time
from pathlib import Path
from playwright.sync_api import sync_playwright,expect
out=Path('/private/tmp/infohub-radius-ux');out.mkdir(exist_ok=True)
token=Path('/private/tmp/infohub-radius-qa/token').read_text().strip()
with sync_playwright() as p:
 browser=p.chromium.launch(headless=True)
 context=browser.new_context(viewport={'width':1440,'height':1000})
 context.add_init_script('localStorage.setItem("infohub_v3_access_token",'+json.dumps(token)+');')
 page=context.new_page();errors=[];page.on('pageerror',lambda e:errors.append(str(e)))
 page.goto('http://127.0.0.1:58232/radius')
 expect(page.get_by_role('navigation').get_by_role('link',name='我的信息半径')).to_be_visible()
 expect(page.get_by_label('向信息半径提问')).to_be_visible()
 expect(page.get_by_role('complementary',name='信息半径概览')).to_contain_text('正文已提取')
 page.screenshot(path=str(out/'01-overview-desktop.png'),full_page=True)
 page.get_by_label('向信息半径提问').fill('AI 陪伴有哪些观点？')
 page.get_by_role('button',name='先查资料',exact=True).click()
 expect(page.get_by_role('region',name='问答资料预览')).to_contain_text('未调用模型')
 page.get_by_role('button',name='发送问题',exact=True).click()
 expect(page.get_by_text('合成材料共同关注',exact=False)).to_be_visible(timeout=20000)
 expect(page.get_by_text('参考来源',exact=False)).to_be_visible()
 page.screenshot(path=str(out/'02-answer-desktop.png'),full_page=True)
 page.locator('.radius-answer-sources button').first.click()
 expect(page.get_by_role('dialog')).to_be_visible()
 expect(page.get_by_role('dialog').locator('article')).to_be_visible()
 page.screenshot(path=str(out/'03-citation-reader.png'),full_page=False)
 page.get_by_role('button',name='关闭阅读').click()
 page.get_by_role('tab',name='浏览与搜索').click()
 page.get_by_label('搜索关注源全文').fill('needleold')
 page.get_by_role('button',name='搜索',exact=True).click()
 expect(page.locator('.radius-article-card')).to_have_count(1)
 page.get_by_role('button',name='阅读',exact=True).click()
 expect(page.get_by_role('dialog').locator('h2').filter(has_text='AI 陪伴的日常使用')).to_be_visible()
 assert page.get_by_role('dialog').locator('p').count()>=3
 page.get_by_label('正文字号').select_option('20')
 assert page.get_by_role('dialog').locator('article p').nth(1).evaluate('(el)=>getComputedStyle(el).fontSize')=='20px'
 expect(page.get_by_role('dialog').locator('blockquote')).to_be_visible()
 page.screenshot(path=str(out/'04-rich-reader.png'),full_page=False)
 page.get_by_role('button',name='问这篇',exact=True).click()
 expect(page.get_by_role('tab',name='AI 问答')).to_have_attribute('aria-selected','true')
 expect(page.get_by_text('仅问这篇：',exact=False)).to_be_visible()
 page.set_viewport_size({'width':390,'height':844})
 page.get_by_role('button',name='新问题',exact=True).click()
 page.screenshot(path=str(out/'05-overview-mobile.png'),full_page=True)
 assert page.evaluate('document.documentElement.scrollWidth<=innerWidth'),'horizontal overflow'
 assert not errors,errors
 (out/'browser-result.json').write_text(json.dumps({'pass':True,'model':'synthetic fixture','flows':['main navigation','direct question without selecting articles','in-place cited answer','citation reader','shared rich reader and type size','ask this article','mobile']},indent=2))
 browser.close()
print('PASS: navigation, automatic retrieval question, answer/citations, shared reader, article question, desktop/mobile')
